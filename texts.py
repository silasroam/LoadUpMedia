# Кадры для визуальной анимации процесса в статусе
PROGRESS_FRAMES: Tuple[str, ...] = ("⏳", "⌛️")


def msg(key: str, **kwargs: object) -> str:
    """Безопасный хелпер для подстановки аргументов в текст.

    Примеры:
        msg("START", name="Аня")   -> готовый текст с именем
        msg("STATUS_PREPARING")    -> текст без подстановок

    Если ключа нет или в шаблоне не хватает плейсхолдеров — возвращает
    исходный шаблон (или подсказку о пропущенном ключе), не падая.
    """
    template = MESSAGES.get(key, f"Missing message for key: {key}")
    try:
        return template.format(**kwargs)
    except Exception:
        return template